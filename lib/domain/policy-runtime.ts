import {
  canonicalizePredicates,
  getRegistryEntry,
  matchRegistryEntry,
  readObservedField,
  readRuntimeField,
  registrySourceQuote,
  renderExpectedCondition,
  validateCanonicalPredicate,
} from "./rule-registry";
import type {
  ExpenseRecord,
  Finding,
  PolicyRule,
  PolicySpec,
  PredicateCondition,
} from "./types";

function compareText(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function conditionPredicates(rule: PolicyRule): readonly PredicateCondition[] {
  if (rule.condition.kind === "predicate") {
    return [rule.condition];
  }
  if (rule.condition.conditions.length < 2 || rule.condition.conditions.length > 3) {
    throw new Error(`Invalid predicate count for ${rule.ruleId}`);
  }
  return rule.condition.conditions;
}

function validateRule(rule: PolicyRule): readonly PredicateCondition[] {
  const predicates = conditionPredicates(rule);
  for (const predicate of predicates) {
    validateCanonicalPredicate(predicate);
  }
  const matched = matchRegistryEntry(predicates);
  const registry = getRegistryEntry(rule.ruleId);
  const canonicalPredicates = canonicalizePredicates(registry, predicates);
  const hasCanonicalOrder = predicates.every((predicate, index) => {
    const canonical = canonicalPredicates[index];
    return (
      canonical !== undefined &&
      predicate.field === canonical.field &&
      predicate.operator === canonical.operator &&
      typeof predicate.value === typeof canonical.value &&
      predicate.value === canonical.value
    );
  });
  if (
    matched.ruleId !== rule.ruleId ||
    !hasCanonicalOrder ||
    rule.outcome !== registry.outcome ||
    rule.label !== registry.label ||
    rule.message !== registry.message ||
    rule.evidenceFields.length !== registry.evidenceFields.length ||
    rule.evidenceFields.some((field, index) => field !== registry.evidenceFields[index]) ||
    rule.sourceQuote !== registrySourceQuote(registry, predicates)
  ) {
    throw new Error(`Rule metadata or structure does not match the registry: ${rule.ruleId}`);
  }
  return predicates;
}

function evaluateValidatedPredicate(
  predicate: PredicateCondition,
  record: ExpenseRecord,
): boolean {
  const actual = readRuntimeField(record, predicate.field);

  switch (predicate.operator) {
    case "missing":
      return actual === null;
    case "eq":
      return typeof actual === typeof predicate.value && actual === predicate.value;
    case "gt":
      return typeof actual === "number" &&
        typeof predicate.value === "number" &&
        actual > predicate.value;
    case "gte":
      return typeof actual === "number" &&
        typeof predicate.value === "number" &&
        actual >= predicate.value;
    case "lt":
      return typeof actual === "number" &&
        typeof predicate.value === "number" &&
        actual < predicate.value;
    case "lte":
      return typeof actual === "number" &&
        typeof predicate.value === "number" &&
        actual <= predicate.value;
  }
}

export function evaluatePredicate(
  predicate: PredicateCondition,
  record: ExpenseRecord,
): boolean {
  validateCanonicalPredicate(predicate);
  return evaluateValidatedPredicate(predicate, record);
}

function createFinding(rule: PolicyRule, record: ExpenseRecord, policyId: PolicySpec["policyId"]): Finding {
  const observed = Object.fromEntries(
    rule.evidenceFields.map((field) => [field, readObservedField(record, field)]),
  );
  return {
    findingKey: `${policyId}|${rule.ruleId}|${record.expenseId}`,
    policyId,
    ruleId: rule.ruleId,
    expenseId: record.expenseId,
    outcome: rule.outcome,
    message: rule.message,
    sourceQuote: rule.sourceQuote,
    observed,
    expectedCondition: renderExpectedCondition(rule),
    sourceRowNumber: record.sourceRowNumber,
  };
}

export function evaluatePolicy(
  spec: PolicySpec,
  records: readonly ExpenseRecord[],
): readonly Finding[] {
  const rules = [...spec.rules].sort((left, right) => compareText(left.ruleId, right.ruleId));
  const sortedRecords = [...records].sort((left, right) =>
    compareText(left.expenseId, right.expenseId),
  );
  const findings: Finding[] = [];

  for (const rule of rules) {
    const predicates = validateRule(rule);
    for (const record of sortedRecords) {
      if (predicates.every((predicate) => evaluateValidatedPredicate(predicate, record))) {
        findings.push(createFinding(rule, record, spec.policyId));
      }
    }
  }

  findings.sort((left, right) => {
    const ruleOrder = compareText(left.ruleId, right.ruleId);
    return ruleOrder === 0 ? compareText(left.expenseId, right.expenseId) : ruleOrder;
  });
  const keys = new Set(findings.map((finding) => finding.findingKey));
  if (keys.size !== findings.length) {
    throw new Error("Duplicate Finding key generated by runtime");
  }
  return findings;
}
